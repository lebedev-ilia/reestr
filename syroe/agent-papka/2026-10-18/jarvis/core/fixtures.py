"""Карантин фикстурных записей, застрявших в живом логе.

Зачем. memory/log — неизменяемая зона: строку оттуда не удалить. Значит
единственный способ не дать проверочному мусору врать в реестре способностей
и в самоаудите — не считать его при ЧТЕНИИ. Течь перекрыта на записи
(memory.mark_live, коммит db7257c: писать в живой лог может только процесс,
поднявший право в точке входа), но всё, что натекло до этого, останется в
логе навсегда.

Правило карантина — два ограничителя, чтобы фильтр не превратился в
«вычищаю всё, что похоже на тест»:
  * по ВРЕМЕНИ — каждая сигнатура закрыта окном. Позже окна фильтр не
    действует НАМЕРЕННО: новая утечка должна ронять самотест, а не тихо
    вычищаться здесь.
  * по СОДЕРЖИМОМУ — совпадение с конкретной фикстурой, а не «похоже на
    проверку». Фильтр по одному лишь имени инструмента запрещён: 25.08
    ручные проверки границ (bl-047/bl-048) налили 210 записей SomeNewTool
    и ещё 134 записи с настоящими именами Write и Bash — отбивать Write
    целиком было бы хуже, чем считать фикстуры.

Куда смотреть, если числа разошлись: modules/audit/daily.py (шлюз по
режимам) и core/registry.py (колонки реестра) — оба спрашивают отсюда.
"""

from datetime import datetime

# Момент, когда заслонка живого лога встала в код (git show db7257c).
# Всё, что легло позже, писалось уже под ней и живое по построению.
GATE_WINDOW_END = datetime.fromisoformat("2026-08-25T21:29:26+10:00")


def _inp(payload: dict) -> str:
    v = payload.get("input")
    return v if isinstance(v, str) else str(v or "")


# (описание — зачем эта строка вообще существует, предикат по payload)
_GATE_SIGNATURES = [
    # 25.08, ручная проверка шлюза по bl-047/bl-048: выдуманный инструмент,
    # которого нет ни в одном списке, — проверялось, что неизвестное уходит
    # в ask/deny, а не выполняется молча. 210 записей.
    ("выдуманный инструмент SomeNewTool",
     lambda p: p.get("tool") == "SomeNewTool"),
    # 25.08, проверка границы «запись вне папки агента»: файл-пустышка /tmp/x.
    ("запись в /tmp/x на проверке границы",
     lambda p: p.get("tool") == "Write" and "/tmp/x" in _inp(p)),
    # 25.08, проверка вечного чёрного списка команд. Команда никогда не
    # выполнялась — шлюз обязан отбить её до запуска.
    ("команда-пустышка sudo rm -rf /",
     lambda p: p.get("tool") == "Bash" and "sudo rm -rf /" in _inp(p)),
    # 25.08, проверка границы раздела 8 «не удалять из memory/log»:
    # выдуманный день 2026-01-01, которого в логе нет и не было.
    ("удаление выдуманного дня из memory/log",
     lambda p: p.get("tool") == "Bash" and "memory/log/2026-01-01.jsonl" in _inp(p)),
]


def is_gate_fixture(payload: dict, ts: str) -> bool:
    """Запись шлюза — след ручной проверки границ, а не живой отказ.

    payload — разобранный content записи type=self с полем gate.
    ts — как записано в логе (смещения разные, +03:00 и +10:00, поэтому
    сравниваются разобранные даты, а не строки).
    """
    if not isinstance(payload, dict) or "gate" not in payload:
        return False
    if not any(pred(payload) for _, pred in _GATE_SIGNATURES):
        return False
    try:
        return datetime.fromisoformat(ts or "") < GATE_WINDOW_END
    except ValueError:
        return False


def gate_signatures() -> list[str]:
    """Описания сигнатур — для самотеста и для отчёта аудита."""
    return [name for name, _ in _GATE_SIGNATURES]
