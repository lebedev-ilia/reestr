"""Мягкое прерывание хода: сообщение Ильи доходит до уже идущей работы.

Задача (Илья, 23.08.2026): «ищешь 10 операций, я пишу что нужно 11 — ты тут же
это видишь, но сразу не прерываешь: сохраняешь, сколько нашёл и на чём
остановился, пишешь мне что принял, и доделываешь уже 11».

Как было. Демон разбирал сообщения строго по одному: пока идёт ход, long-poll
не опрашивается, новое сообщение лежит в очереди ВК. Илья получал ответ на
устаревший вопрос, а работа делалась второй раз.

Как стало. Пока идёт ход из ВК, отдельная задача демона читает историю диалога
и складывает новые сообщения сюда. Забирает их отсюда шлюз разрешений
(core/agent.make_gate): перед очередным вызовом инструмента он видит, что
что-то пришло, и возвращает агенту decision=deny с текстом сообщения и
инструкцией. Это не запрет действия, а единственный способ вложить новый текст
в идущий ход: у SDK нет канала «дослать сообщение в работающий query».

Почему именно так, а не разрыв хода: разорванный ход теряет всё, что успел
надумать, и его пришлось бы начинать заново — то есть ровно та двойная работа,
от которой мы уходим. Здесь агент остаётся в своём контексте, ему стоит одного
пропущенного вызова инструмента (он его повторяет следом) — и он сам решает,
что зафиксировать и как учесть новое.

Состояние живёт в памяти процесса, а не в файле: оно осмысленно ровно на время
одного хода. Потеря при перезапуске безвредна — непрочитанное сообщение
остаётся в очереди ВК и будет разобрано обычным путём.
"""
from __future__ import annotations

import threading

# Сколько раз за один ход можно вбросить новое сообщение. Предохранитель от
# ситуации «Илья пишет каждые десять секунд»: иначе ход будет состоять из
# одних прерываний и не сдвинется. Лишнее не теряется — уходит в leftover().
MAX_PER_TURN = 5

_lock = threading.Lock()
_armed = False
_paused = False
_queue: list[dict] = []      # {"text": str, "msg": dict, "taken": bool}
_taken = 0


def arm() -> None:
    """Начало хода, в который можно вбрасывать. Зовёт демон ВК."""
    global _armed, _paused, _queue, _taken
    with _lock:
        _armed, _paused, _queue, _taken = True, False, [], 0


def disarm() -> list[dict]:
    """Конец хода. Возвращает сообщения, которые агент так и не увидел.

    Такое бывает, когда сообщение пришло в самом конце хода — инструментов
    больше не будет, вбросить некуда. Демон обрабатывает их обычным ходом:
    молча проглотить сообщение Ильи хуже, чем ответить на него отдельно.
    """
    global _armed
    with _lock:
        _armed = False
        left = [item for item in _queue if not item["taken"]]
        _queue.clear()
        return left


def pause(flag: bool) -> None:
    """Пауза на время, когда историю диалога читает кто-то ещё (ask).

    Без неё «да» на вопрос разрешения перехватывалось бы как прерывание,
    и ответ Ильи не дошёл бы до того, кто его ждёт.
    """
    global _paused
    with _lock:
        _paused = flag


def paused() -> bool:
    with _lock:
        return _paused or not _armed


def armed() -> bool:
    with _lock:
        return _armed


def push(text: str, msg: dict | None = None) -> bool:
    """Новое сообщение пришло во время хода. False — вбрасывать некуда."""
    with _lock:
        if not _armed:
            return False
        _queue.append({"text": (text or "").strip(), "msg": msg or {}, "taken": False})
        return True


def pending() -> bool:
    with _lock:
        return any(not item["taken"] for item in _queue)


def take() -> list[str]:
    """Забрать непрочитанное. Зовёт шлюз перед вызовом инструмента."""
    global _taken
    with _lock:
        if not _armed or _taken >= MAX_PER_TURN:
            return []
        fresh = [item for item in _queue if not item["taken"]]
        if not fresh:
            return []
        for item in fresh:
            item["taken"] = True
        _taken += 1
        return [item["text"] for item in fresh if item["text"]]


TASK = """⚠ ЭТО НЕ ЗАПРЕТ ДЕЙСТВИЯ И НЕ ОШИБКА. Пока ты работал, Илья написал:

{texts}

Порядок:
1. Не бросай сделанное. Одной строкой держи в голове (а лучше запиши в файл \
или в ответ), что уже готово и на чём ты остановился.
2. Прочитай новое сообщение как поправку к текущей задаче: цель могла \
измениться, объём вырасти, приоритет смениться. Если оно про другое — доделай \
текущее и ответь на него в конце.
3. Продолжай в этом же ходе, уже с учётом нового. Действие, которое ты сейчас \
пытался сделать, не запрещено — повтори его, если оно всё ещё нужно.

Ничего Илье ещё не ушло — но пересказывать его слова не надо, отвечай по делу."""

QUESTION = """⚠ ЭТО НЕ ЗАПРЕТ ДЕЙСТВИЯ И НЕ ОШИБКА. Илья задал ВОПРОС \
посреди работы:

{texts}

Вопрос — не поручение. Ждать конца работы нельзя: ответ нужен сейчас и почти \
всегда уже есть у тебя в голове.

Порядок:
1. СНАЧАЛА ответь — одним сообщением, по факту, цифрой если спрашивают \
количество. Отправь немедленно:
   .venv/bin/python -m jarvis.modules.vk.notify "твой ответ"
2. Не пересказывай вопрос и не пиши «принял». Просто ответь.
3. Нечем ответить точно — скажи, сколько есть на этот момент и чего не хватает.
4. Потом повтори прерванное действие и продолжай: оно не запрещено."""

# Признаки вопроса. Намеренно грубо и с запасом: ошибиться в сторону «это
# вопрос» дешевле — лишний быстрый ответ никому не мешает, а пропущенный
# вопрос заставляет Илью ждать до конца работы (25.08.2026).
_Q_WORDS = ("сколько", "что ", "как ", "какой", "какие", "каков", "когда",
            "где", "почему", "зачем", "кто ", "чем ", "куда", "ты уже",
            "нашёл", "нашел", "успел", "готово", "есть ли", "можешь ли",
            "долго", "на каком", "статус", "ответь", "скажи", "покажи",
            "получилось", "получается", "далеко", "много ли")


def looks_like_question(text: str) -> bool:
    """Вопрос ли это.

    Слова ищутся ГДЕ УГОДНО в коротком сообщении, а не только в начале:
    настоящая фраза Ильи 25.08.2026 была «ты мне ответь, сколько контактов
    ты уже нашёл?» — по началу строки такое не ловится вовсе.

    Длинный текст под это правило не подпадает: там «сколько» может стоять
    посреди поручения, и остановка на быстрый ответ только помешает.
    """
    t = (text or "").strip().lower()
    if not t:
        return False
    if "?" in t:
        return True
    if len(t) > 200:
        return False
    return any(w in t for w in _Q_WORDS)


def notice(texts: list[str]) -> str:
    body = "\n".join(f"  «{t}»" for t in texts)
    NOTICE = QUESTION if any(looks_like_question(t) for t in texts) else TASK
    return NOTICE.format(texts=body)
