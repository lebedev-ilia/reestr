import io

p = "/home/jarvis/agent/jarvis/memory/agents/konsol-frontend/ROLE.yaml"
t = io.open(p, encoding="utf-8").read()

old = """Уложился раньше — не стоишь: берёшь копилку практик,
    ищешь в интернете ещё, записываешь найденное в knowledge/ и ищешь
    плохие элементы у себя. Пустой заход допустим только если демон
    занят чужой работой."""

