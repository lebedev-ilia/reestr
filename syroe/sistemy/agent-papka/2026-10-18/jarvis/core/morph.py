"""Морфология для поиска по памяти: приведение слова к основе.

Зачем. Память теперь — оглавление плюс поиск, и поиск сравнивал подстроки:
запрос «письмо» не находил «письма», «письмам», «письмах». Длинный хвост,
ради которого recall и существует, наполовину не искался.

Почему свой стеммер, а не библиотека. Ставить pymorphy2/nltk ради одной
функции — лишняя зависимость в ядре, которое должно запускаться где угодно
и не ломаться от чужих релизов. Здесь классический алгоритм Snowball для
русского: он весь на регулярках, детерминирован и укладывается в сотню строк.

Что он делает и чего не делает. Отрезает окончания и часть суффиксов:
«письма» → «письм», «квартиру» → «квартир», «отправленный» → «отправлен».
Не сводит разные корни к одному («иду»/«шёл» останутся разными) и иногда
склеивает неродственное — для поиска это допустимая цена: лучше лишний
кандидат в выдаче, чем пропущенное попадание.
"""
import re
from functools import lru_cache

# --------------------------------------------------------------------------
# Snowball для русского. Регулярки — канонические, менять их наугад нельзя:
# порядок альтернатив и группы важны, проверяется core/selftest.py.
# --------------------------------------------------------------------------

_RV = re.compile(r"^(.*?[аеиоуыэюя])(.*)$")
_PERFECTIVE = re.compile(r"((ив|ивши|ившись|ыв|ывши|ывшись)|((?<=[ая])(в|вши|вшись)))$")
_REFLEXIVE = re.compile(r"(с[яь])$")
_ADJECTIVE = re.compile(
    r"(ее|ие|ые|ое|ими|ыми|ей|ий|ый|ой|ем|им|ым|ом|его|ого|ему|ому|их|ых|ую|юю"
    r"|ая|яя|ою|ею)$")
_PARTICIPLE = re.compile(r"((ивш|ывш|ующ)|((?<=[ая])(ем|нн|вш|ющ|щ)))$")
_VERB = re.compile(
    r"((ила|ыла|ена|ейте|уйте|ите|или|ыли|ей|уй|ил|ыл|им|ым|ен|ило|ыло|ено|ят"
    r"|ует|уют|ит|ыт|ены|ить|ыть|ишь|ую|ю)"
    r"|((?<=[ая])(ла|на|ете|йте|ли|й|л|ем|н|ло|но|ет|ют|ны|ть|ешь|нно)))$")
_NOUN = re.compile(
    r"(а|ев|ов|ие|ье|е|иями|ями|ами|еи|ии|и|ией|ей|ой|ий|й|иям|ям|ием|ем|ам|ом"
    r"|о|у|ах|иях|ях|ы|ь|ию|ью|ю|ия|ья|я)$")
_DERIVATIONAL = re.compile(r"[^аеиоуыэюя][аеиоуыэюя]+[^аеиоуыэюя]+[аеиоуыэюя].*(?<=о)сть?$")
_DER = re.compile(r"ость?$")
_SUPERLATIVE = re.compile(r"(ейше|ейш)$")
_I = re.compile(r"и$")
_SOFT = re.compile(r"ь$")
_NN = re.compile(r"нн$")

_LATIN = re.compile(r"^[a-z0-9]+$")
_WORD = re.compile(r"[a-zа-яё0-9]+")

# Служебные слова: в запрос попадают случайно, а совпадают почти со всем.
STOP = {
    "и", "в", "во", "не", "что", "он", "на", "я", "с", "со", "как", "а", "то",
    "все", "она", "так", "его", "но", "да", "ты", "к", "у", "же", "вы", "за",
    "бы", "по", "ее", "мне", "было", "вот", "от", "меня", "еще", "нет",
    "о", "из", "ему", "теперь", "когда", "даже", "ну", "вдруг", "ли", "если",
    "уже", "или", "ни", "быть", "был", "него", "до", "вас", "нибудь", "опять",
    "уж", "вам", "ведь", "там", "потом", "себя", "ничего", "ей", "может",
    "они", "тут", "где", "есть", "надо", "ней", "для", "мы", "тебя", "их",
    "чем", "была", "сам", "чтоб", "без", "будто", "чего", "раз", "тоже",
    "себе", "под", "будет", "ж", "тогда", "кто", "этот", "того", "потому",
    "этого", "какой", "совсем", "ним", "здесь", "этом", "один", "почти",
    "мой", "тем", "чтобы", "нее", "были", "куда", "зачем", "всех", "никогда",
    "можно", "при", "наконец", "два", "об", "другой", "хоть", "после", "над",
    "больше", "тот", "через", "эти", "нас", "про", "всего", "них", "какая",
    "много", "разве", "три", "эту", "моя", "впрочем", "хорошо", "свою",
    "этой", "перед", "иногда", "лучше", "чуть", "том", "нельзя", "такой",
    "им", "более", "всегда", "конечно", "всю", "между",
}


@lru_cache(maxsize=100_000)
def stem(word: str) -> str:
    """Основа слова. Латиница и цифры проходят почти как есть."""
    w = word.lower().replace("ё", "е")
    if _LATIN.match(w):
        # Минимум для английского: множественное число. Дальше не лезем —
        # ing/ed сводят к одному слишком разное.
        return w[:-1] if len(w) > 3 and w.endswith("s") and not w.endswith("ss") else w

    m = _RV.match(w)
    if not m:
        return w
    pre, rv = m.groups()

    temp = _PERFECTIVE.sub("", rv, 1)
    if temp == rv:
        rv = _REFLEXIVE.sub("", rv, 1)
        temp = _ADJECTIVE.sub("", rv, 1)
        if temp != rv:
            rv = _PARTICIPLE.sub("", temp, 1)
        else:
            temp = _VERB.sub("", rv, 1)
            rv = _NOUN.sub("", rv, 1) if temp == rv else temp
    else:
        rv = temp

    rv = _I.sub("", rv, 1)
    if _DERIVATIONAL.search(rv):
        rv = _DER.sub("", rv, 1)
    temp = _SOFT.sub("", rv, 1)
    if temp == rv:
        rv = _NN.sub("н", _SUPERLATIVE.sub("", rv, 1), 1)
    else:
        rv = temp
    return pre + rv


def tokens(text: str) -> list[str]:
    """Слова текста в нижнем регистре, ё → е."""
    return _WORD.findall(text.lower().replace("ё", "е"))


def stems(text: str) -> set[str]:
    """Множество основ текста — то, с чем сравнивается запрос."""
    return {stem(t) for t in tokens(text) if len(t) > 1}


_ALPHABET = "абвгдежзийклмнопрстуфхцчшщъыьэюя"


def _variants(s: str) -> frozenset[str]:
    """Основы, отличающиеся от s ровно одной буквой на конце.

    Snowball иногда режет на букву больше или меньше: «память» → «памя», но
    «памяти» → «памят»; «отправить» → «отправ», но «отправлено» → «отправл».
    Допуск в одну букву чинит именно этот класс промахов и не пускает
    «стол» в «столицу» — там расхождение в две буквы.
    """
    if len(s) < 4:
        return frozenset()
    v = {s[:-1]} if len(s) >= 5 else set()
    v |= {s + c for c in _ALPHABET}
    return frozenset(v)


def prepare(query: str) -> tuple[list[tuple[str, frozenset[str]]], list[str], list[str]]:
    """Разбор запроса на то, чем по нему искать.

    Возвращает (основы с допуском, буквальные куски, исходные слова).

    Буквальные — всё, где есть дефис, точка, слэш или цифры вперемешку с
    буквами: «bl-004», «now.md», «memory/log». Их морфология только испортит,
    и ищутся они подстрокой, как раньше.
    """
    raw = query.lower().replace("ё", "е")
    parts = [p for p in re.split(r"\s+", raw) if p]
    literals, words = [], []
    for p in parts:
        core = p.strip(".,;:!?()«»\"'")
        if not core:
            continue
        if re.search(r"[^a-zа-я]", core) and len(core) > 2:
            literals.append(core)
        else:
            words.append(core)
    st = sorted({stem(w) for w in words if len(w) > 1 and w not in STOP} - {""})
    terms = [(s, _variants(s)) for s in st if len(s) > 1]
    return terms, literals, words


def score(text: str, query) -> float:
    """Насколько текст отвечает запросу. 0 — не отвечает вовсе.

    Главный вклад даёт полнота: документ, где нашлись все слова запроса,
    всегда выше документа с одним. Точная форма слова добавляет немного —
    при прочих равных «письма» ближе к запросу «письма», чем «письмо».
    Совпадение по допуску в одну букву считается за неполное.
    """
    terms, literals, words = query
    total = len(terms) + len(literals)
    if not total:
        return 0.0
    low = text.lower().replace("ё", "е")
    doc = stems(text)

    hit = 0.0
    found = 0
    for s, variants in terms:
        if s in doc:
            hit += 1.0
            found += 1
        elif variants & doc:
            hit += 0.7
            found += 1
    for l in literals:
        if l in low:
            hit += 1.0
            found += 1
    if not found:
        return 0.0

    s = 10.0 * (hit / total)
    if found == total:
        s += 2.0
    s += 0.4 * sum(1 for w in words if len(w) > 2 and w in low)
    return s
