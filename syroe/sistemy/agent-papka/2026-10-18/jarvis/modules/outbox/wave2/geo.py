def _base_name(city: str) -> str:
    """Часть строки до скобки или запятой — то, что обычно и есть сам город."""
    cut = re.split(r"[,(]", city, maxsplit=1)[0].strip()
    return cut


def offset_for(city: str) -> tuple[int, bool]:
    """(смещение от UTC в часах, опознан ли город).

    Неопознанный город получает Москву (+3) — это ближайшее к "по умолчанию
    правильно" для пула, где Москва и так 98 карточек из 340, — но с
    resolved=False, чтобы вызывающий код мог показать это в отчёте, а не
    молча разослать по чужому времени.
    """
    if not city:
        return MOSCOW_OFFSET, False
    if city in CITY_TZ:
        return CITY_TZ[city], True
    base = _base_name(city)
    if base in BASE_TZ:
        return BASE_TZ[base], True
    return MOSCOW_OFFSET, False


def unresolved(cities: list[str]) -> list[str]:
    """Из списка городов — те, что offset_for не смог опознать (без повтора)."""
    seen: list[str] = []
    for c in cities:
        _, ok = offset_for(c)
        if not ok and c not in seen:
            seen.append(c)
    return seen
