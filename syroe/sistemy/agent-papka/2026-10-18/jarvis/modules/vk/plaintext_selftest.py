"""Проверка modules/vk/plaintext.py: markdown → текст для ВК.

Каждый случай: вход, что обязано быть в выводе, чего быть не должно.
Запуск: ./.venv/bin/python -m jarvis.modules.vk.plaintext_selftest
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from jarvis.modules.vk import plaintext as P  # noqa: E402

CASES = [
    ("жирный и курсив",
     "**Главное:** это *важно* и `модуль.py`",
     ["Главное:", "важно", "модуль.py"], ["**", "`", "*важно*"]),

    ("заголовок",
     "## Итог дня\nВсё сделано",
     ["Итог дня:", "Всё сделано"], ["##"]),

    ("список",
     "Сделал:\n- письма ушли\n- notion почищен\n1. проверить утром",
     ["— письма ушли", "— notion почищен", "— проверить утром"], ["- пись", "1."]),

    ("таблица разворачивается в строки",
     "| id | что | статус |\n|----|-----|--------|\n| cap-001 | канал ВК | ok |",
     ["cap-001", "что: канал ВК", "статус: ok"], ["|", "----"]),

    ("ссылка markdown",
     "Смотри [реестр](https://ex.ru/a) тут",
     ["реестр: https://ex.ru/a"], ["[", "](" ]),

    ("горизонтальная линия убирается",
     "первое\n\n---\n\nвторое",
     ["первое", "второе"], ["---"]),

    ("длинный абзац рубится",
     ("Сегодня ушли первые десять писем настоящим контактам. "
      "Ответов пока нет, и это нормально для первого дня. "
      "Проверять входящие буду раз в сутки до двадцать шестого августа. "
      "Если отлупов не будет, отправлю следующую порцию тем же каркасом. "
      "Каркас показал себя рабочим на пилоте по своим ящикам."),
     ["\n\n"], []),

    ("код не портится",
     "Запусти:\n```\npython -m jarvis.modules.vk.check\n```",
     ["python -m jarvis.modules.vk.check"], ["```"]),

    ("обычный короткий ответ не трогается",
     "Готово, письма ушли.",
     ["Готово, письма ушли."], ["\n"]),
]


def main() -> int:
    bad = []
    for name, src, must, must_not in CASES:
        got = P.render(src)
        for m in must:
            if m not in got:
                bad.append(f"[{name}] нет «{m}» в:\n{got}")
        for m in must_not:
            if m in got:
                bad.append(f"[{name}] осталось «{m}» в:\n{got}")
    if bad:
        print("✗ форматирование ВК:")
        for b in bad:
            print("  " + b.replace("\n", "\n    "))
        return 1
    print(f"✓ форматирование ВК: {len(CASES)} случаев")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
