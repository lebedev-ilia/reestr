def live_env(extra: dict | None = None) -> dict:
    """Окружение для subprocess.Popen долгоживущего процесса: копия текущего
    окружения без _INHERIT_NEVER, плюс что попросили добавить (extra).

    Звать в КАЖДОМ месте, где subprocess.Popen поднимает процесс, который
    должен пережить вызвавший его ход: core/restart.py (демон, наблюдатель),
    core/jobs.py (воркер подагента). Разовые скрипты (git, pgrep и т.п.)
    этой функции не касаются — им наследовать флаги можно, они не живут
    дольше своего вызова.
    """
    env = dict(os.environ)
    for name in _INHERIT_NEVER:
        env.pop(name, None)
    if extra:
        env.update(extra)
    return env


